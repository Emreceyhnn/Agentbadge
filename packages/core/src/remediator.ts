import type { ScanResult } from './types.js';

export interface RemediationOptions {
  existingContent?: string;
  packageManager?: 'pnpm' | 'npm' | 'yarn' | 'bun';
  isMonorepo?: boolean;
}

const PATCH_HEADER = '## 🤖 Agent Readiness Patch (Added by agentbadge audit';

export function generateRemediationAgentsMd(scan: ScanResult, options?: RemediationOptions): string {
  const pm = options?.packageManager || 'npm';
  const runPrefix = pm === 'npm' ? 'npm run' : pm;
  const installCmd = pm === 'npm' ? 'npm install' : `${pm} install`;

  // If existing AGENTS.md content is provided, append/replace the patch section idempotently
  if (options?.existingContent && options.existingContent.trim().length > 0) {
    let cleanExisting = options.existingContent.trim();
    // Strip previous agentbadge patch section if already present
    const patchIndex = cleanExisting.indexOf(PATCH_HEADER);
    if (patchIndex !== -1) {
      cleanExisting = cleanExisting.substring(0, patchIndex).trim();
      // Remove trailing horizontal rule if present
      cleanExisting = cleanExisting.replace(/---\s*$/, '').trim();
    }

    const missingItems: string[] = [];

    if (scan.pillars.verification.score < scan.pillars.verification.maxScore) {
      missingItems.push(`### Verification Fast Loops
Add/verify the following execution scripts:
\`\`\`bash
${runPrefix} type-check
${runPrefix} lint
${pm === 'npm' ? 'npm test' : `${pm} test`}
\`\`\``);
    }

    if (scan.pillars.setup.score < scan.pillars.setup.maxScore) {
      missingItems.push(`### Setup & Secrets
Make sure required environment variables are copied from \`.env.example\`:
\`\`\`bash
cp .env.example .env
${installCmd}
\`\`\``);
    }

    return `${cleanExisting}

---

${PATCH_HEADER} — Score: ${scan.score}/100)
${missingItems.length > 0 ? missingItems.join('\n\n') : '- Codebase meets core verification and setup guardrails.'}
`;
  }

  // Generate complete boilerplate if no AGENTS.md exists yet
  return `# AGENTS.md — Repository Operating Instructions for AI Agents

> **Auto-generated by agentbadge audit.**
> This file gives AI coding agents (Claude Code, Cursor, Copilot, Codex, Devin) the direct context required to build, test, and navigate this codebase without hallucination.

---

## 1. Project Overview & Boundaries
- **Project Name:** ${scan.repoName || 'Project'}
- **Current Readiness Score:** ${scan.score}/100 (${scan.tier})
- **Architecture Philosophy:** Maintain strict typing, modular separation of concerns, and clean contracts.

---

## 2. Setup & Environment
Run these commands to prepare your local development environment:
\`\`\`bash
# Bootstrap dependencies
${installCmd}
cp .env.example .env
\`\`\`

---

## 3. Verification & Fast Feedback Loops
Always verify changes locally before committing:
\`\`\`bash
# 1. Type Check
${runPrefix} type-check

# 2. Linting
${runPrefix} lint

# 3. Automated Tests
${pm === 'npm' ? 'npm test' : `${pm} test`}
\`\`\`

---

## 4. Key Rules for Agents
- **Zero \`any\` policy:** Explicit typing only.
- **Fail fast:** Run verification commands after modifying code.
- **Do not bypass git hooks or CI checks.**
- Document all architectural decisions and API models explicitly.
`;
}
